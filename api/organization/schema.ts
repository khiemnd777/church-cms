const oid = { bsonType: "objectId" },
  date = { bsonType: "date" },
  integer = { bsonType: ["int", "long", "double"], minimum: 0 };
const stamps = {
  version: { ...integer, minimum: 1 },
  writeFence: integer,
  createdAt: date,
  updatedAt: date,
  createdBy: oid,
  updatedBy: oid,
  createdByKind: { enum: ["owner", "church_user"] },
  updatedByKind: { enum: ["owner", "church_user"] },
};
const required = Object.keys(stamps);
export const organizationSchemas = {
  organization_terms: {
    required: [
      "_id",
      "churchId",
      "label",
      "startOn",
      "endOn",
      "state",
      "appointments",
      ...required,
    ],
    additionalProperties: false,
    properties: {
      _id: oid,
      churchId: oid,
      ...stamps,
      label: { bsonType: "string", minLength: 1, maxLength: 100 },
      startOn: { bsonType: ["string", "null"] },
      endOn: { bsonType: ["string", "null"] },
      closedOn: { bsonType: "string" },
      lastEffectiveOn: { bsonType: "string" },
      state: { enum: ["draft", "confirmed", "ended", "cancelled"] },
      appointments: {
        bsonType: "array",
        maxItems: 100,
        items: {
          bsonType: "object",
          additionalProperties: false,
          required: ["memberId", "code", "fullName", "position"],
          properties: {
            memberId: oid,
            code: { bsonType: "string" },
            fullName: { bsonType: "string" },
            position: { enum: ["secretary", "treasurer", "deacon"] },
          },
        },
      },
    },
  },
  organization_history: {
    required: [
      "_id",
      "churchId",
      "targetId",
      "event",
      "effectiveOn",
      "reason",
      "actorId",
      "actorKind",
      "occurredAt",
      "before",
      "after",
    ],
    properties: {
      _id: oid,
      churchId: oid,
      targetId: oid,
      event: { bsonType: "string" },
      effectiveOn: { bsonType: "string" },
      reason: { bsonType: "string" },
      actorId: oid,
      actorKind: { enum: ["owner", "church_user"] },
      occurredAt: date,
      before: { bsonType: ["object", "null"] },
      after: { bsonType: "object" },
    },
  },
  church_settings: {
    required: ["_id", ...required, "unitType", "defaultAssignmentMode"],
    additionalProperties: false,
    properties: {
      _id: oid,
      ...stamps,
      unitType: { enum: ["area", "cell_group", "branch", "custom"] },
      customUnitLabel: { bsonType: "string", minLength: 1, maxLength: 40 },
      defaultAssignmentMode: { enum: ["auto", "manual"] },
    },
    oneOf: [
      { required: ["customUnitLabel"], properties: { unitType: { enum: ["custom"] } } },
      {
        properties: { unitType: { enum: ["area", "cell_group", "branch"] } },
        not: { required: ["customUnitLabel"] },
      },
    ],
  },
  organization_units: {
    required: ["_id", ...required, "churchId", "kind", "namespace", "name", "nameKey", "status"],
    additionalProperties: false,
    properties: {
      _id: oid,
      ...stamps,
      churchId: oid,
      kind: { enum: ["board", "age_ministry", "service_ministry", "area"] },
      namespace: { enum: ["ministry", "area"] },
      systemKey: { enum: ["board", "children", "teens", "youth", "adults", "seniors"] },
      name: { bsonType: "string", minLength: 1, maxLength: 100 },
      leaderMemberId: { bsonType: ["objectId", "null"] },
      scheduleText: { bsonType: ["string", "null"], maxLength: 500 },
      nameKey: { bsonType: "string", minLength: 1, maxLength: 200 },
      status: { enum: ["active", "inactive"] },
    },
    oneOf: [
      {
        required: ["systemKey"],
        properties: {
          kind: { enum: ["board", "age_ministry"] },
          namespace: { enum: ["ministry"] },
          status: { enum: ["active"] },
        },
      },
      {
        properties: { kind: { enum: ["service_ministry"] }, namespace: { enum: ["ministry"] } },
        not: { required: ["systemKey"] },
      },
      {
        properties: { kind: { enum: ["area"] }, namespace: { enum: ["area"] } },
        not: { required: ["systemKey"] },
      },
    ],
  },
};
